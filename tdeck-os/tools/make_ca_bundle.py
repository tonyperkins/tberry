#!/usr/bin/env python3
"""Build the CA certificate bundle the update client uses to check HTTPS servers.

Usage:  python3 tools/make_ca_bundle.py [ca-certificates.crt] [include/ca_bundle.h]

Reads a PEM file of trusted root certificates (default: the system store, which is Mozilla's list)
and writes it in the format of ESP-IDF's x509 bundle: a 16-bit count, then for each certificate
the lengths of its subject and public key followed by their DER bytes, sorted by subject. The
firmware passes it to WiFiClientSecure::setCACertBundle().

Roots expire and change, so regenerate this from time to time and ship it with an update.
"""
import struct, sys
from cryptography import x509
from cryptography.hazmat.primitives import serialization

src = sys.argv[1] if len(sys.argv) > 1 else "/etc/ssl/certs/ca-certificates.crt"
dst = sys.argv[2] if len(sys.argv) > 2 else "include/ca_bundle.h"

pem = open(src, "rb").read()
certs = []
for block in pem.split(b"-----END CERTIFICATE-----"):
    if b"-----BEGIN CERTIFICATE-----" not in block:
        continue
    try:
        c = x509.load_pem_x509_certificate(block + b"-----END CERTIFICATE-----\n")
    except Exception:
        continue
    subject = c.subject.public_bytes()
    key = c.public_key().public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
    certs.append((subject, key))

certs = sorted(set(certs))
out = struct.pack(">H", len(certs))
for subject, key in certs:
    out += struct.pack(">HH", len(subject), len(key)) + subject + key

with open(dst, "w") as f:
    f.write("#pragma once\n// Generated by tools/make_ca_bundle.py: %d root certificates, %d bytes.\n" % (len(certs), len(out)))
    f.write("static const unsigned char CA_BUNDLE[%d] = {\n" % len(out))
    for i in range(0, len(out), 16):
        f.write("  " + ", ".join("0x%02x" % b for b in out[i:i + 16]) + ",\n")
    f.write("};\n")
print(f"{len(certs)} certificates, {len(out)} bytes -> {dst}")
